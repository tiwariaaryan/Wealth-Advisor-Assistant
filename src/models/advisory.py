from typing import List, Optional
from datetime import datetime
from pydantic import BaseModel, Field

class AdvisoryRecommendation(BaseModel):
    category: str = Field(..., description="E.g. Portfolio Rebalancing, Risk Mitigation, Tax Optimization, Cash Deployment")
    priority: str = Field(..., description="URGENT, HIGH, MEDIUM, LOW")
    action_title: str = Field(..., description="Short title for action item")
    detailed_guidance: str = Field(..., description="Clear, actionable instructions for client/advisor")
    rationale: str = Field(..., description="Economic or risk justification based on client's profile")

class RebalanceItem(BaseModel):
    asset_class: str = Field(..., description="Asset class being rebalanced")
    current_percent: float = Field(..., description="Current allocation %")
    target_percent: float = Field(..., description="Target allocation % from CRM")
    adjustment_action: str = Field(..., description="INCREASE, DECREASE, or MAINTAIN")
    suggested_dollar_shift: float = Field(..., description="Estimated dollar amount to rebalance")

class AdvisoryReport(BaseModel):
    client_id: str = Field(..., description="Client identifier")
    client_name: str = Field(..., description="Client name")
    executive_summary: str = Field(..., description="High-level overview of portfolio health, key issues, and strategy")
    risk_alignment_score: str = Field(..., description="E.g. 'Strong Alignment (92%)' or 'Severe Misalignment (45%)'")
    flagged_anomalies_summary: List[str] = Field(default_factory=list, description="Summary of anomalies evaluated")
    recommendations: List[AdvisoryRecommendation] = Field(default_factory=list, description="Prioritized recommendations")
    rebalance_plan: List[RebalanceItem] = Field(default_factory=list, description="Structured rebalance table")
    advisor_override_notes: Optional[str] = Field(default=None, description="Human advisor overrides incorporated into report")
    compliance_disclaimer: str = Field(
        default="This report is generated by an AI Wealth Advisor Assistant for advisory simulation. Past performance is no guarantee of future results.",
        description="Standard fiduciary compliance disclaimer"
    )
    generated_at: str = Field(default_factory=lambda: datetime.now().isoformat(), description="Timestamp of generation")
